/* ============================================================================
   Render the REAL printed sheet, from the app's own engine, to a file you can
   open in a browser and print.

   This is not a mock-up: it boots the actual app in jsdom, seeds a plausible
   log, and calls the same printSheet() the Print card button calls. If the
   sheet is wrong, this file is wrong.

       node design/build-live-sheet.js
       open design/print-sheet-live.html
   ========================================================================== */
const fs = require('fs');
const path = require('path');
const { JSDOM, VirtualConsole } = require(path.join(__dirname, '..', 'app', 'node_modules', 'jsdom'));

const APP = path.join(__dirname, '..', 'app');
const OUT = path.join(__dirname, 'print-sheet-live.html');

function read(p) { return fs.readFileSync(path.join(APP, p), 'utf8'); }

/* Inline the app the way build.py does, so jsdom boots deterministically. */
function inlineApp() {
  let html = read('index.html');
  html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) =>
    '<style>' + read(href) + '</style>');
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) =>
    '<script>' + read(src) + '<\/script>');
  return html;
}

const SEED = `
(() => {
  const s = getState();
  s.onboarded = true; s.consented = true;
  Object.assign(s.profile, {
    name:'Yanis', experience:'i', goal:'h', goals:['h'], equipment:'gym',
    shiftType:'night', sleepHours:5.5, sleepVariability:2, usualWake:7,
    style:'hit', daysPerWeek:3, sessionMinutes:50, unit:'kg', bodyweight:112
  });
  s.plan = buildPlan(s.profile);
  const DAY = 864e5, now = Date.now();
  const key = ms => { const d = new Date(ms), p = n => (n<10?'0':'')+n;
    return d.getFullYear()+'-'+p(d.getMonth()+1)+'-'+p(d.getDate()); };

  /* four weeks of training, so the sheet has a real "last time" and a real
     availability figure rather than a first-run blank */
  const days = [26, 23, 21, 18, 16, 13, 11, 8, 6, 3];
  days.forEach((ago, i) => {
    const sn = s.plan.sessions[i % s.plan.sessions.length];
    s.sessions.push({
      id: 'seed' + ago, date: now - ago*DAY, planId: sn.id, name: sn.name, focus: sn.focus,
      exercises: sn.exercises.map((e, ei) => ({
        id: e.id,
        sets: Array.from({length: e.sets}, (_, k) => ({
          w: 55 + ei*5 + Math.round(i*1.25), r: 8, rir: k ? 0 : 1,
          warmup:false, skipped:false, committed:true
        }))
      }))
    });
  });
  /* a rotating night-shift week */
  [0,1,2,4,5].forEach((ago, i) => {
    s.sleep.push({ id:'sl'+ago, start: key(now-ago*DAY)+'T23:30', end: key(now-(ago-1)*DAY)+'T05:20', quality:3 });
  });
  [1,2,3,5].forEach(ago => {
    s.shifts.push({ id:'sh'+ago, start: key(now-ago*DAY)+'T19:00', end: key(now-(ago-1)*DAY)+'T07:00' });
  });
  saveState();
})();
`;

const vc = new VirtualConsole();
const dom = new JSDOM(inlineApp(), {
  runScripts: 'dangerously', pretendToBeVisual: true,
  url: 'https://localhost/ancestor/index.html', virtualConsole: vc
});
const win = dom.window;
win.scrollTo = () => {};
if (typeof win.boot === 'function') win.boot();
win.eval(SEED);

const next = win.eval('nextSession(getState(), Date.now()).session.id');
const sheet = win.eval(`printSheet(getState(), Date.now(), { planId: '${next}' })`);

