#!/usr/bin/env node
/* ============================================================================
   ANCESTOR — module boundaries, declared and enforced

       node tools/modules.js            -> writes js/MODULES.md
       node tools/modules.js --check    -> fails if js/MODULES.md is stale

   The app is 43 classic scripts sharing one global scope, and it has to stay
   that way: `index.html` is opened from the file system, and ES modules are
   blocked by CORS on `file://`. So "add module boundaries" cannot mean import
   statements. What it can mean, and what this file does, is make the boundaries
   *explicit and checked*:

     - one owner per top-level name. Two files declaring `round1` is not a style
       problem; whichever loads last silently wins, and the other copy is dead
       code that looks alive.
     - every file on disk is actually loaded, and every load is a file on disk.
     - the number of names each file owns is recorded and ratcheted: adding a
       global means updating this manifest in the same commit, on purpose.
     - what each file reaches for across a boundary is listed, so a dependency
       that should not exist is visible before it becomes load-order folklore.

   The manifest is generated, not hand-written, for the same reason the figure
   geometry is: a document about the code that nobody regenerates is fiction.
   ========================================================================== */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const MANIFEST = path.join(ROOT, 'js/MODULES.md');
const CHECK = process.argv.includes('--check');

/* ---- 1. the load order, taken from index.html, which is the real one ------ */
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const loaded = [];
const re = /<script src="(js\/[^"]+\.js)"><\/script>/g;
let m;
while ((m = re.exec(html))) loaded.push(m[1]);

/* ---- 2. every file on disk, so a dead file is impossible to miss ---------- */
function walk(dir, out) {
  for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = dir + '/' + e.name;
    if (e.isDirectory()) { if (e.name !== 'vendor') walk(rel, out); }
    else if (e.name.endsWith('.js') && rel !== 'js/sw.js') out.push(rel);
  }
  return out;
}
const onDisk = walk('js', []).sort();

/* ---- 3. who owns which top-level name ------------------------------------- */
/* Column 0 only: an indented declaration is a local, and locals are the one
   thing that already has a boundary. */
const DECL = /^(?:async\s+)?(?:function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)/;
const OWNERS = new Map();   // name -> [file]
const PROVIDES = new Map(); // file -> [name]
const SOURCE = new Map();

for (const f of loaded) {
  const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
  SOURCE.set(f, src);
  const names = [];
  for (const line of src.split('\n')) {
    const d = DECL.exec(line);
    if (d && !names.includes(d[1])) names.push(d[1]);
  }
  PROVIDES.set(f, names);
  for (const n of names) {
    if (!OWNERS.has(n)) OWNERS.set(n, []);
    OWNERS.get(n).push(f);
  }
}

const GLOBAL = new Set(OWNERS.keys());
const DUPLICATES = [...OWNERS].filter(([, files]) => files.length > 1);
const UNLOADED = onDisk.filter(f => !loaded.includes(f));
const MISSING = loaded.filter(f => !fs.existsSync(path.join(ROOT, f)));

/* ---- 4. cross-boundary references, as a reading aid ----------------------- */
/* This is a token scan, not a resolver: it says "this file mentions a name it
   does not own", which is exactly the list a person wants when asking whether
   `screens.js` should know about `readiness.js` at all. */
const TOKEN = /[A-Za-z_$][\w$]*/g;
const requires = new Map();
for (const f of loaded) {
  const own = new Set(PROVIDES.get(f));
  const seen = new Set();
  const body = SOURCE.get(f).replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ');
  for (const t of body.match(TOKEN) || []) {
    if (GLOBAL.has(t) && !own.has(t)) seen.add(t);
  }
  requires.set(f, [...seen].sort());
}

/* ---- 5. the manifest ------------------------------------------------------ */
const total = GLOBAL.size;
const lines = [];
lines.push('# Module boundaries');
lines.push('');
lines.push('> Generated by `node tools/modules.js`. Do not hand-edit: `--check` fails the');
lines.push('> build if this file and the code disagree.');
lines.push('');
lines.push('The app is 43 classic scripts in one global scope, and it has to stay that');
lines.push('way: `index.html` must open from the file system, and `file://` blocks ES');
lines.push('modules. So the boundary is a contract rather than a syntax — one owner per');
lines.push('name, no unloaded files, and a count per file that cannot grow by accident.');
lines.push('');
lines.push(`**${loaded.length} files, ${total} top-level names.** Each name has exactly one`);
lines.push('owner; `provides` is what a file creates, `reaches for` is what it mentions');
lines.push('from another file (a token scan, so it over-reports — it is a reading list,');
lines.push('not a dependency graph).');
lines.push('');
lines.push('| # | File | Provides | Reaches for |');
lines.push('|---:|---|---:|---:|');
loaded.forEach((f, i) => {
  const n = PROVIDES.get(f).length;
  const r = requires.get(f).length;
  lines.push(`| ${i + 1} | \`${f}\` | ${n} | ${r} |`);
});
lines.push('');
lines.push('## Who owns what');
lines.push('');
lines.push('The full map, in load order. A name appears once; if it ever appears twice,');
lines.push('`--check` fails and names both files.');
lines.push('');
for (const f of loaded) {
  const names = PROVIDES.get(f);
  lines.push(`- **\`${f}\`** — ${names.length}${names.length ? ': `' + names.join('` `') + '`' : ''}`);
}
lines.push('');

const text = lines.join('\n');
const problems = [];
if (DUPLICATES.length) {
  for (const [n, files] of DUPLICATES) problems.push(`\`${n}\` is declared in ${files.join(' and ')}`);
}
if (UNLOADED.length) problems.push(`never loaded by index.html: ${UNLOADED.join(', ')}`);
if (MISSING.length) problems.push(`loaded but absent from disk: ${MISSING.join(', ')}`);

if (CHECK) {
  let stale = '';
  try { stale = fs.readFileSync(MANIFEST, 'utf8'); } catch (e) { stale = ''; }
  const drift = stale !== text;
  if (drift) {
    const wasLines = stale.split('\n'), nowLines = text.split('\n');
    const at = wasLines.findIndex((l, i) => l !== nowLines[i]);
    problems.push(`js/MODULES.md is stale (first difference at line ${at + 1}) — run \`node tools/modules.js\``);
  }
  if (problems.length) {
    console.error('\n  MODULE BOUNDARY CHECK FAILED\n');
    problems.forEach(p => console.error('   - ' + p));
    console.error('');
    process.exit(1);
  }
  console.log(`  boundaries hold — ${loaded.length} files, ${total} names, one owner each`);
} else {
  if (problems.length) {
    console.error('\n  cannot write a manifest that lies:\n');
    problems.forEach(p => console.error('   - ' + p));
    console.error('');
    process.exit(1);
  }
  fs.writeFileSync(MANIFEST, text);
  console.log(`  wrote js/MODULES.md — ${loaded.length} files, ${total} names, ${text.length} bytes`);
}
